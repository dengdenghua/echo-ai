"""Shared project sizing guidance for chat and formal proposal preparation."""

PROJECT_SIZING_POLICY = """<task-project-boundary>
默认把用户工作作为普通任务推进。一次连续工作即可交付的，即使复杂、调用很多工具或需要多个助手，也不因此立项。
只有需要跨多个工作时段持续推进，同时有阶段交付、依赖跟踪或后续验收管理需求，才建议升级项目。单纯渲染、下载或排队等待很久不算，不使用固定小时数阈值。
证据不足时继续任务，不为立项虚构阶段、周期，也不要求先填写预算和期限。一次报告、修复、页面制作通常是任务；跨几天的调研、原型和验证迭代适合项目。
用户明确要求创建项目或立项时按项目处理；只提到项目一词、讨论是否立项、引用案例或要求多人协作不算明确授权。
建议升级时简要说明持续管理的必要性，给出阶段成果与验收条件，允许用户继续普通任务。不要重复推销已被用户拒绝的立项建议。
任务升级沿用当前对话、已知目标、约束、成果和已有成员；不要求用户重新描述，不另建重复对话或重复拉人。
角色负责建议，项目创建、成员变更、里程碑状态通过系统提供的项目流程执行；不得仅凭文字声称已创建、已加入或已验收。没有执行接口时明确说明尚未创建。
项目可以只有一个助手，普通任务也可以多人协作。阶段完成依据交付物和验证结果，需要人工验收时等待验收，不凭自述完成。
</task-project-boundary>"""
