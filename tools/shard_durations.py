"""Refresh ``tests/shard_durations.json`` from a GitHub Actions pytest log.

CI splits the full suite into shards (``ECHO_TEST_SHARD=i/N``, see
``tests/sharding.py``). Files that take at least ``--min-seconds`` are placed
by their recorded duration so the shards finish together; every other file is
spread by a hash of its path. Refresh the numbers when shards drift apart:

    gh run view --job <full-suite job id> --log > job.log
    python tools/shard_durations.py job.log

Several shard logs can be passed at once; their files are merged.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "tests" / "shard_durations.json"

# pytest's default (non -q) progress: "tests/test_x.py ....   [ 12%]", with
# long files continuing on lines of bare outcome characters.
_FILE_LINE = re.compile(r"(\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d\.\d+)Z (tests/\S+\.py) ")
_CONTINUATION = re.compile(r"(\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d\.\d+)Z [.sFExX]+\s+\[")


def durations_from_log(lines: list[str]) -> dict[str, float]:
    """Seconds per test file, measured between progress-line timestamps."""

    durations: dict[str, float] = {}
    previous_time: datetime | None = None
    current_file: str | None = None
    for line in lines:
        match = _FILE_LINE.search(line)
        if match is not None:
            path: str | None = match.group(2)
        else:
            match = _CONTINUATION.search(line)
            if match is None:
                continue
            path = current_file
        stamp = datetime.fromisoformat(match.group(1)[:26])
        if previous_time is not None and path is not None:
            durations[path] = durations.get(path, 0.0) + (stamp - previous_time).total_seconds()
        previous_time, current_file = stamp, path
    return durations


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("logs", nargs="+", type=Path, help="GitHub Actions job logs")
    parser.add_argument("--min-seconds", type=float, default=2.0)
    args = parser.parse_args(argv)

    measured: dict[str, float] = {}
    for log in args.logs:
        lines = log.read_text(encoding="utf-8", errors="replace").splitlines()
        measured.update(durations_from_log(lines))
    if not measured:
        print("no pytest progress lines found", file=sys.stderr)
        return 1
    heavy = {
        path: round(seconds, 1)
        for path, seconds in sorted(measured.items())
        if seconds >= args.min_seconds and (ROOT / path).is_file()
    }
    payload = {
        "note": "Generated by tools/shard_durations.py; CI shard placement for slow files.",
        "min_seconds": args.min_seconds,
        "files": heavy,
    }
    text = json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    total = sum(measured.values()) / 60
    print(f"{len(heavy)} of {len(measured)} files recorded ({total:.1f} min measured)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
