const copies: Record<Locale, AssistantActivityCopy> = {
  "en-US": en,
  "zh-CN": zh,
  "ja-JP": ja,
  "ko-KR": ko,
};

export function assistantActivityCopy(
  locale: string | boolean,
): AssistantActivityCopy {
  return copies[
    normalizeLocale(
      typeof locale === "boolean" ? (locale ? "zh-CN" : "en-US") : locale,
    )
  ];
}

export function activityStatusLabel(
  status: string,
  copy: AssistantActivityCopy,
): string {
  const labels: Readonly<Record<string, string>> = copy.statuses;
  return Object.hasOwn(labels, status)
    ? (labels[status] ?? status)
    : status || "—";
}

export function activityReason(
  reason: string,
  copy: AssistantActivityCopy,
): string {
  if (reason === "execution_completed") return copy.executionCompleted;
  const linked = reason.startsWith("run:");
  const status = linked ? reason.slice(4) : reason;
  if (!Object.hasOwn(copy.reasons, status)) return reason;
  const labels: Readonly<Record<string, string>> = copy.reasons;
  const label = labels[status] ?? reason;
  return linked ? `${copy.linkedRun}${label}` : label;
}
